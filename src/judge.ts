function normalizeRisk(value: unknown): JudgeVerdict["risk"] | undefined {
  if (typeof value !== "string") return undefined;
  const v = value.trim().toLowerCase();
  return v === "low" || v === "medium" || v === "high" ? v : undefined;
}

function normalizeRecommend(value: unknown): JudgeVerdict["recommend"] | undefined {
  if (typeof value !== "string") return undefined;
  const v = value.trim().toLowerCase();
  if (v === "allow" || v === "approve" || v === "yes") return "allow";
  if (v === "deny" || v === "block" || v === "no") return "deny";
  return undefined;
}

/** Extract and validate a judge verdict from fenced or bare model JSON.
 *  A verdict needs at least one usable signal (risk or recommend); output
 *  with neither is unparseable and fails closed downstream. */
export function parseJudgeVerdict(text: string): JudgeVerdict | null {
  if (!text) return null;
  const fenced = text.match(/```(?:json)?\s*([\s\S]*?)```/);
  const raw = fenced ? fenced[1] : text;
  const match = raw.match(/\{[\s\S]*\}/);
  if (!match) return null;
  try {
    const value: unknown = JSON.parse(match[0]);
    if (!value || typeof value !== "object" || Array.isArray(value)) return null;
    const v = value as Record<string, unknown>;
    const risk = normalizeRisk(v.risk);
    const recommend = normalizeRecommend(v.recommend);
    if (!risk && !recommend) return null;
    const summary = typeof v.summary === "string" && v.summary.trim() ? v.summary.trim() : undefined;
    return {
      ...(risk ? { risk } : {}),
      ...(recommend ? { recommend } : {}),
      ...(summary ? { summary } : {}),
    };
  } catch {
    return null;
  }
}

/** Project a classified prompt outcome onto the judge result surface:
 *  completed text is parsed into a verdict (unparseable text degrades to
 *  empty — the policy then fails closed); null means the judge is
 *  unavailable (invoker disposed or the request was pre-aborted). */
export function outcomeFromPrompt(outcome: PromptOutcome | null): JudgeOutcome {
  if (outcome === null) return { kind: "unavailable", reason: "judge unavailable" };
  switch (outcome.kind) {
    case "text": {
      const verdict = parseJudgeVerdict(outcome.text);
      if (verdict) return { kind: "verdict", verdict };
      return { kind: "empty", reason: "unparseable verdict" };
    }
    case "empty":
      return { kind: "empty", reason: outcome.reason };
    case "error":
      return { kind: "error", reason: outcome.reason, category: toJudgeErrorCategory(outcome.category) };
  }
}

/** Tunables for one JudgeInvoker. All are optional; defaults below. */
export interface JudgeInvokerOptions {
  /** Idle lifetime of the persistent judge child, in ms.
   *  0 = keep alive until dispose. Default 10 minutes. */
  idleMs?: number;
  /** Window for the per-assessment new_session ack and prompt.
   *  0 = no timeout. Default 30 s. */
  analysisTimeoutMs?: number;
  /** Grace before SIGKILL escalation on dispose. Default 5 s. */
  disposeGraceMs?: number;
  /** Grace before child retirement if an abort is not acknowledged.
   *  Default 5 s. */
  abortGraceMs?: number;
}

/**
 * Remove a request-owned abort listener exactly once. A settled request must
 * not keep a listener that can fire later against a NEWER request's
 * pending/reset state. Called from every settlement path.
 */
function detachedAbortListener(signal: AbortSignal | undefined, listener: ((ev: Event) => void) | undefined): void {
  if (signal && listener) signal.removeEventListener("abort", listener);
}

/**
 * Whether a new_session response authorizes the prompt: successful ack, AND
 * the session is not cancelled. A cancelled session is not a fresh one, so
 * the reset must fail closed and the prompt must never dispatch.
 */
function newSessionOutcome(frame: { success?: boolean; error?: string; data?: unknown }): {
  authorized: boolean;
  reason: string;
} {
  const data = frame.data;
  let cancelled = false;
  if (data !== null && typeof data === "object" && "cancelled" in data) {
    cancelled = (data as Record<string, unknown>).cancelled === true;
  }
  if (frame.success === true && !cancelled) return { authorized: true, reason: "acked" };
  if (frame.error) return { authorized: false, reason: `rejected: ${frame.error}` };
  if (frame.success !== true) return { authorized: false, reason: "not successful" };
  return { authorized: false, reason: "session already cancelled" };
}

interface PendingPrompt {
  timer: NodeJS.Timeout | undefined;
  abortTimer: NodeJS.Timeout | undefined;
  /** Outbound prompt id whose matching response authorizes lifecycle frames. */
  id: string;
  /** True after a successful response for this exact prompt id. */
  promptAccepted: boolean;
  /** True only after this prompt's agent_start frame has arrived. */
  agentStarted: boolean;
  /** True when the request was aborted by its AbortSignal (abort
   *  classification at settlement, distinct from an empty completion). */
  aborted: boolean;
  /** Resolves the assess promise exactly once, with the classified
   *  outcome. Stored on the pending so settlement is a single idempotent
   *  operation at the cause site. */
  resolve: (outcome: PromptOutcome) => void;
  /** Accumulated text_delta deltas; the diagnostic signal for
   *  reasoning-only vs empty distinction (never the verdict itself). */
  deltaBuffer: string;
  /** True once at least one text_delta streamed for this prompt. */
  deltaArrived: boolean;
  /** Wall-clock time the first text_delta arrived (first-output latency). */
  firstDeltaAt: number | undefined;
  /** Wall-clock entry time of runPrompt for this attempt (+Nms in logs). */
  startedAt: number;
  /** The classified result, written exactly once on settlement. */
  outcome: PromptOutcome | undefined;
  /** The request's AbortSignal (undefined when none) — the listener owner. */
  signal: AbortSignal | undefined;
  /** The removable abort listener; detached exactly once on settlement. */
  abortListener: ((ev: Event) => void) | undefined;
}

/** In-flight new_session reset: the id whose matching ack authorizes the prompt. */
interface ResetAck {
  id: string;
  timer: NodeJS.Timeout | undefined;
  resolve: (authorized: boolean) => void;
  signal: AbortSignal | undefined;
  abortListener: ((ev: Event) => void) | undefined;
}

