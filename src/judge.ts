/**
 * `--config` overlay for the judge child.  `--no-rules` leaves discovered
 * context files in the system prompt: a large project AGENTS.md would add
 * tens of thousands of prompt tokens per verdict — past the assessment
 * window, so every assessment failed closed.  With the overlay the same
 * verdict costs a few hundred tokens.  `unexpectedStopDetection: none`
 * drops the extra model call the child otherwise makes on each verdict.
 */
export const JUDGE_CONFIG_OVERLAY = [
  "# Generated by auto-approve for its isolated judge worker; rewritten on every spawn.",
  "disabledExtensions:",
  ...CONTEXT_FILE_NAMES.flatMap((name) => [`  - context-file:user:${name}`, `  - context-file:project:${name}`]),
  "features:",
  "  unexpectedStopDetection: none",
  "",
].join("\n");

/** Materialize the overlay under `dir` and return its path. Rewritten only
 *  when the content differs, so a hand-edited copy is always restored. */
export function writeJudgeOverlay(dir: string): string {
  const file = path.join(dir, "auto-approve-judge.yml");
  let current: string | null = null;
  try {
    current = fs.readFileSync(file, "utf-8");
  } catch {}
  if (current !== JUDGE_CONFIG_OVERLAY) {
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(file, JUDGE_CONFIG_OVERLAY);
  }
  return file;
}

/**
 * Child argv for the judge. `configOverlay` is the path from
 * writeJudgeOverlay; it is required so no spawn path can silently
 * reintroduce repo-context bloat.
 */
export function buildJudgeArgs(
  model: string,
  configOverlay: string,
  opts: { systemPrompt?: string } = {},
): string[] {
  const systemPrompt = opts.systemPrompt ?? JUDGE_SYSTEM_PROMPT;
  return [
    "--mode", "rpc",
    "--model", model,
    `--config=${configOverlay}`,
    `--system-prompt=${systemPrompt}`,
    "--no-tools",
    "--no-session",
    "--no-lsp",
    "--no-skills",
    "--no-rules",
    "--no-title",
    "--no-prewalk",
    "--no-pty",
    "--no-extensions",
    "--thinking=off",
    "--max-time=300",
  ];
}

/** Cap the command sent into a prompt so a pathological command cannot
 *  blow the model window. */
function truncateSubject(command: string, maxChars: number): string {
  if (command.length <= maxChars) return command;
  return `${command.slice(0, maxChars)}\n[... truncated: ${command.length - maxChars} more characters]`;
}

