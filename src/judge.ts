/**
 * Auto Approve — persistent RPC judge invoker.
 *
 * Spawns ONE `omp --mode rpc` child process and reuses it for every
 * one-shot risk assessment, instead of cold-starting the judge per call.
 * This amortizes process startup across assessments.
 *
 * Protocol (omp RPC, NDJSON on stdio):
 *   - ready frame on spawn; `new_session` is acked per reset
 *   - every assessment starts with a new_session reset and proceeds only
 *     when the child acks that exact id (statelessness guarantee)
 *   - `prompt` is acknowledged immediately; completion arrives via
 *     `agent_end` (messages) events
 *   - `abort` cancels the in-flight prompt (request signal / timeout)
 *
 * The child is lazily spawned on first use, reaped after the idle window,
 * and killed on dispose. A crashed child is respawned on the next call.
 * The protocol machinery is a port of smart-approve's battle-tested
 * RpcModelInvoker (reset correlation, generation fencing, settlement).
 */

