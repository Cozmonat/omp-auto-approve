function defaultChildFactory(launch: RpcLaunchSpec): RpcChildFactory {
  return (model) => {
    const overlay = writeJudgeOverlay(getConfigDir());
    const args = [...launch.prefixArgs, ...buildJudgeArgs(model, overlay)];
    return child_process.spawn(launch.command, args, {
      stdio: ["pipe", "pipe", "pipe"],
      env: { ...process.env, PI_MEMORY_BACKEND: "off" },
    });
  };
}

/** Child factory for the deep-analysis invoker: identical spawn shape to
 *  the verdict child, but the system prompt is the prose analyst prompt,
 *  so the two passes never share a child or a prompt contract. */
export function makeDeepChildFactory(launch: RpcLaunchSpec): RpcChildFactory {
  return (model) => {
    const overlay = writeJudgeOverlay(getConfigDir());
    const args = [...launch.prefixArgs, ...buildJudgeArgs(model, overlay, { systemPrompt: JUDGE_DEEP_SYSTEM_PROMPT })];
    return child_process.spawn(launch.command, args, {
      stdio: ["pipe", "pipe", "pipe"],
      env: { ...process.env, PI_MEMORY_BACKEND: "off" },
    });
  };
}

/**
 * Drives one persistent judge child: lazy spawn, per-assessment
 * new_session reset, serialized prompts, timeout/abort handling, idle
 * reap, and dispose. Ported from smart-approve's RpcModelInvoker with the
 * model-switch pool stripped (single child, model taken at spawn).
 */
export class JudgeInvoker {
  private proc: RpcChild | null = null;
  private rl: readline.Interface | null = null;
  private currentModel: string | null = null;
  private seq = 0;
  private pending: PendingPrompt | null = null;
  private resetAck: ResetAck | null = null;
  private chain: Promise<PromptOutcome | null> = Promise.resolve(null);
  /** Process-local stable instance id (log-only): keeps concurrent plugin
   *  instances' logs from colliding on the shared `aa-N` sequence. */
  private readonly instanceId: string;
  /** Child generation: bumped on every spawn; `gen=N` in logs tells which
   *  child a frame or event belongs to. */
  private generation = 0;
  private idleTimer: NodeJS.Timeout | null = null;
  private readonly launch: RpcLaunchSpec;
  private readonly logger: LoggerLike;
  private readonly idleMs: number;
  private readonly analysisTimeoutMs: number;
  private readonly childFactory: RpcChildFactory;
  private readonly disposeGraceMs: number;
  private readonly abortGraceMs: number;
  private disposed = false;

  constructor(
    launch: RpcLaunchSpec,
    logger: LoggerLike,
    options: JudgeInvokerOptions = {},
    childFactory?: RpcChildFactory,
  ) {
    this.launch = launch;
    this.logger = logger;
    this.instanceId = `aa-${(Math.random().toString(16).slice(2, 6) || "0000")}`;
    this.idleMs = options.idleMs ?? DEFAULT_IDLE_MS;
    this.analysisTimeoutMs = options.analysisTimeoutMs ?? DEFAULT_ANALYSIS_TIMEOUT_MS;
    this.disposeGraceMs = options.disposeGraceMs ?? DEFAULT_DISPOSE_GRACE_MS;
    this.abortGraceMs = options.abortGraceMs ?? DEFAULT_ABORT_GRACE_MS;
    this.childFactory = childFactory ?? defaultChildFactory(launch);
  }

  /** True when a spawn attempt has been made and the process is alive. */
  get isAlive(): boolean {
    return !!this.proc && this.proc.exitCode === null && this.proc.signalCode === null;
  }

  /** Run one risk assessment on the given model spec.
   *  Returns the classified judge outcome; null projections (judge
   *  disposed, pre-aborted request) surface as `unavailable`. */
  assess(model: string, promptText: string, opts: {
    timeoutMs: number;
    signal?: AbortSignal;
  }): Promise<JudgeOutcome> {
    if (this.disposed) return Promise.resolve({ kind: "unavailable", reason: "judge unavailable" });
    return this.promptWithOutcome(model, promptText, opts).then((outcome) =>
      outcome === null ? { kind: "unavailable", reason: "judge unavailable" } : outcomeFromPrompt(outcome),
    );
  }

  /** Run a one-shot prompt and return the classified outcome (raw protocol
   *  surface); `assess` is the judge-level wrapper that parses verdicts. */
  promptWithOutcome(model: string, promptText: string, opts: {
    timeoutMs: number;
    signal?: AbortSignal;
  }): Promise<PromptOutcome | null> {
    if (this.disposed) return Promise.resolve(null);
    this.chain = enqueueSerialized(this.chain, () => this.runPrompt(model, promptText, opts));
    return this.chain;
  }

  /** Kill the child process (dispose, model switch, or idle reap).
   *  Settles any in-flight prompt to error — a prompt must never outlive
   *  its child. */
  kill(): void {
    if (this.idleTimer) {
      clearTimeout(this.idleTimer);
      this.idleTimer = null;
    }
    const proc = this.proc;
    if (proc && proc.exitCode === null && proc.signalCode === null) {
      this.logger.log(`judge: [${this.instanceId}/- gen=${this.generation}] retired (process killed)`);
      proc.kill("SIGTERM");
      const escalation = setTimeout(() => {
        if (proc.exitCode === null && proc.signalCode === null) {
          this.logger.log("judge: kill grace elapsed, SIGKILL");
          proc.kill("SIGKILL");
        }
      }, this.abortGraceMs);
      escalation.unref?.();
      proc.on("exit", () => clearTimeout(escalation));
    }
    this.proc = null;
    this.rl?.close();
    this.rl = null;
    if (this.resetAck) this.resolveReset(false, "process killed");
    this.failPending("process killed", "exit");
  }

  /**
   * Terminate the child and await its exit (SIGTERM, then SIGKILL if it
   * survives the grace window). Idempotent and safe to await repeatedly; any
   * in-flight prompt settles.
   */
  async dispose(): Promise<void> {
    if (this.disposed) return;
    this.disposed = true;
    if (this.idleTimer) {
      clearTimeout(this.idleTimer);
      this.idleTimer = null;
    }
    if (this.resetAck) this.resolveReset(false, "disposed");
    const proc = this.proc;
    this.logger.log(`judge: [${this.instanceId}/- gen=${this.generation}] retired (disposed)`);
    this.failPending("disposed", "exit");
    if (!proc || !this.isAlive) {
      this.proc = null;
      this.rl?.close();
      this.rl = null;
      return;
    }
    const { promise, resolve } = Promise.withResolvers<void>();
    let settled = false;
    const grace = setTimeout(() => {
      if (!settled && this.isAlive) {
        this.logger.log("judge: dispose grace elapsed, SIGKILL");
        proc.kill("SIGKILL");
      }
    }, this.disposeGraceMs);
    grace.unref?.();
    const onExit = () => {
      if (settled) return;
      settled = true;
      clearTimeout(grace);
      resolve();
    };
    proc.on("exit", onExit);
    if (!this.isAlive) return onExit();
    this.logger.log("judge: disposing judge invoker process (SIGTERM)");
    proc.kill("SIGTERM");
    await promise;
    this.proc = null;
    this.rl?.close();
    this.rl = null;
  }

  // ── internals ─────────────────────────────────────────────────────

  /** One bounded, tagged lifecycle log line. `gen` names the child generation;
   *  `+Nms` is monotonic duration from the prompt's runPrompt entry. Never
   *  carries prompt, command, or conversation text. */
  private logEvent(gen: number, id: string, fromMs: number, event: string, details = ""): void {
    const dur = Math.max(0, Math.round(Date.now() - fromMs));
    this.logger.log(`judge: [${this.instanceId}/${id} gen=${gen}] ${event} +${dur}ms${details ? ` ${details}` : ""}`);
  }

  private async runPrompt(
    model: string,
    promptText: string,
    opts: { timeoutMs: number; signal?: AbortSignal },
  ): Promise<PromptOutcome | null> {
    if (opts.signal?.aborted) return null;
    // Re-check for work enqueued before dispose: the serialized chain can
    // execute it after the latch closed — fail closed, never respawn.
    if (this.disposed) return null;
    const attemptDeadline = opts.timeoutMs > 0 ? Date.now() + opts.timeoutMs : Infinity;

    // Ensure the child runs with the requested model; respawn on spec change.
    // (When the model matches and the child is healthy, reuse it as-is —
    // startup cost is paid once per host session.)
    if (model !== this.currentModel || !this.isAlive) {
      this.logger.log(`judge: model change ${this.currentModel ?? "(none)"} -> ${model}, restarting`);
      this.kill();
      const spawnRemaining = attemptDeadline - Date.now();
      if (spawnRemaining <= 0) {
        this.logger.log("judge: deadline exhausted before child startup");
        return { kind: "error", reason: "deadline exhausted before child startup", category: "timeout" };
      }

      let spawnTimer: NodeJS.Timeout | undefined;
      let spawnAbortListener: (() => void) | undefined;
      try {
        const spawning = this.spawn(model);
        const readyRemaining = attemptDeadline - Date.now();
        if (readyRemaining <= 0) {
          void spawning.catch((e) => {
            this.logger.log(`judge: expired child exited before ready (${e instanceof Error ? e.message : String(e)})`);
          });
          this.logger.log("judge: deadline exhausted during child startup");
          this.kill();
          return { kind: "error", reason: "deadline exhausted during child startup", category: "timeout" };
        }
        const waits: Array<Promise<"ready" | "timeout" | "aborted">> = [
          spawning.then(() => "ready" as const),
        ];
        if (Number.isFinite(readyRemaining)) {
          const timeout = Promise.withResolvers<"timeout">();
          spawnTimer = setTimeout(
            () => timeout.resolve("timeout"),
            Math.max(1, Math.floor(readyRemaining)),
          );
          waits.push(timeout.promise);
        }
        if (opts.signal) {
          const aborted = Promise.withResolvers<"aborted">();
          spawnAbortListener = () => aborted.resolve("aborted");
          opts.signal.addEventListener("abort", spawnAbortListener, { once: true });
          if (opts.signal.aborted) spawnAbortListener();
          waits.push(aborted.promise);
        }

        const outcome = await Promise.race(waits);
        if (outcome !== "ready") {
          const category: ProtocolErrorCategory =
            outcome === "timeout" ? "timeout" : outcome === "aborted" ? "abort" : "spawn";
          const desc = outcome === "timeout"
            ? "child startup timed out before ready"
            : outcome === "aborted"
              ? "child startup aborted"
              : "child startup exited before ready";
          this.logger.log(`judge: ${desc} (${outcome})`);
          this.kill();
          return { kind: "error", reason: desc, category };
        }
      } catch (e) {
        const spawnError = e instanceof Error ? e.message : String(e);
        this.logger.log(`judge: spawn failed (${redactForLog(spawnError)})`);
        return { kind: "error", reason: redactForLog(spawnError), category: "spawn" };
      } finally {
        clearTimeout(spawnTimer);
        if (spawnAbortListener) opts.signal?.removeEventListener("abort", spawnAbortListener);
      }
    }
    // Spawn settled: if the child died in between, fail closed.
    if (!this.isAlive) {
      this.logger.log("judge: child unavailable after spawn");
      this.kill();
      return { kind: "error", reason: "child unavailable after spawn", category: "spawn" };
    }

    // Cancel any pending idle reap — the child is active again.
    if (this.idleTimer) {
      clearTimeout(this.idleTimer);
      this.idleTimer = null;
    }
    // Per-assessment stateless reset: every assessment begins with
    // new_session and proceeds only if THIS child generation acks THAT id
    // within the remaining attempt window. Spawn and reset time consume the
    // same timeout budget as verdict generation.
    const resetId = `aa-${++this.seq}`;
    const startedAt = Date.now();
    const resetRemaining = attemptDeadline - Date.now();
    if (resetRemaining <= 0) {
      this.logger.log(`judge: deadline exhausted before new_session ${resetId}`);
      this.kill();
      return { kind: "error", reason: "deadline exhausted before new_session", category: "timeout" };
    }
    const resetWindowMs = Number.isFinite(resetRemaining)
      ? Math.max(1, Math.min(this.analysisTimeoutMs, Math.floor(resetRemaining)))
      : this.analysisTimeoutMs;
    const resetAuthorized = await this.performReset(resetId, resetWindowMs, opts.signal);
    if (!resetAuthorized) {
      this.logger.log(`judge: new_session reset not authorized (${resetId}), judge unavailable`);
      this.kill();
      return { kind: "error", reason: "new_session reset not authorized", category: "timeout" };
    }

    // Cancellation may land between the reset ack and the prompt write
    // (no prompt after cancellation).
    if (opts.signal?.aborted) {
      this.logger.log(`judge: cancelled before prompt (after new_session ${resetId})`);
      return null;
    }

    const id = `aa-${++this.seq}`;
    this.logEvent(this.generation, id, startedAt, "prompt sent", `model=${model}`);

    const promptRemaining = attemptDeadline - Date.now();
    if (promptRemaining <= 0) {
      this.logger.log(`judge: deadline exhausted before prompt ${id}`);
      this.kill();
      return { kind: "error", reason: "deadline exhausted before prompt", category: "timeout" };
    }

    const { promise, resolve } = Promise.withResolvers<PromptOutcome>();
    const pending: PendingPrompt = {
      timer: undefined,
      abortTimer: undefined,
      id,
      promptAccepted: false,
      agentStarted: false,
      aborted: false,
      resolve,
      deltaBuffer: "",
      deltaArrived: false,
      firstDeltaAt: undefined,
      startedAt,
      outcome: undefined,
      signal: opts.signal,
      abortListener: undefined,
    };
    this.pending = pending;

    // Reap the child after the idle window if no further prompt arrives.
    const promptTimeoutMs = Number.isFinite(promptRemaining)
      ? Math.max(1, Math.floor(promptRemaining))
      : 0;
    if (promptTimeoutMs > 0) {
      pending.timer = setTimeout(() => {
        if (this.pending?.id !== id) return;
        this.logger.log(`judge: prompt ${id} timed out after ${promptTimeoutMs}ms, retiring child`);
        // Settle the timeout at the cause site BEFORE the kill, so the
        // retirement's process-exit cannot reclassify it as "exit".
        this.settle({ kind: "error", reason: `prompt timed out after ${promptTimeoutMs}ms`, category: "timeout" });
        this.write({ type: "abort" });
        this.kill();
      }, promptTimeoutMs);
    }

    // Capture this child generation; the idle reaper may only reap the child
    // that this settled request actually used (no cross-generation reap).
    const genProc = this.proc;
    promise.finally(() => {
      // Prompt settled — arm the idle reaper for the next quiet window.
      if (this.idleMs > 0) {
        this.idleTimer = setTimeout(() => {
          if (this.proc !== genProc) return;
          this.logger.log(`judge: idle ${this.idleMs}ms, reaping child`);
          this.kill();
        }, this.idleMs);
        this.idleTimer.unref?.();
      }
      if (pending.outcome) {
        const details =
          pending.outcome.kind === "error"
            ? `kind=error category=${pending.outcome.category}`
            : pending.outcome.kind === "empty"
              ? `kind=empty reason=${pending.outcome.reason}`
              : "kind=text";
        this.logEvent(this.generation, id, startedAt, "terminal", details);
      }
    });

    // Request-owned abort listener: it must target THIS request's pending
    // (never the current one, which may already be a later request) and must
    // be detached on settlement.
    const onAbort = () => {
      if (this.pending !== pending) return;
      pending.aborted = true;
      this.logger.log(`judge: prompt ${id} aborted by signal`);
      this.abort();
    };
    if (opts.signal) {
      pending.abortListener = onAbort;
      if (opts.signal.aborted) onAbort();
      else opts.signal.addEventListener("abort", onAbort, { once: true });
    }

    this.write({
      id,
      type: "prompt",
      message: promptText,
    });

    return promise;
  }

  /**
   * Send the new_session reset for this assessment and resolve once the
   * child's ack authorizes the prompt: successful ack carrying THIS id, on
   * this live child generation, within the window. A missing, late, or
   * mismatched ack resolves false (fail-closed) without sending the prompt.
   */
  private performReset(id: string, windowMs: number, signal?: AbortSignal): Promise<boolean> {
    this.clearResetAck();
    const { promise, resolve } = Promise.withResolvers<boolean>();
    const ack: ResetAck = { id, timer: undefined, resolve, signal, abortListener: undefined };
    this.resetAck = ack;

    const timer = setTimeout(
      () => this.resolveReset(false, `no ack within ${windowMs}ms`),
      Math.max(1, windowMs),
    );
    timer.unref?.();
    ack.timer = timer;

    if (signal) {
      // Request-owned reset abort listener: identity-fenced to THIS ack so a
      // later request's reset can never be resolved by an old signal, and
      // detached on settlement.
      const onAbort = () => {
        if (this.resetAck !== ack) return;
        this.resolveReset(false, "aborted");
      };
      ack.abortListener = onAbort;
      if (signal.aborted) {
        this.resolveReset(false, "aborted");
      } else {
        signal.addEventListener("abort", onAbort, { once: true });
      }
    }

    this.logger.log(`judge: new_session ${id} (per-assessment reset)`);
    this.write({ id, type: "new_session" });
    // The ack (or its absence) settles the promise through resolveReset.
    return promise;
  }

  /** Single settlement point for the in-flight reset (ack, window, abort, kill). */
  private resolveReset(authorized: boolean, why: string): void {
    const ack = this.resetAck;
    if (!ack) return;
    this.resetAck = null;
    if (ack.timer) clearTimeout(ack.timer);
    detachedAbortListener(ack.signal, ack.abortListener);
    if (!authorized) this.logger.log(`judge: new_session ${ack.id} not authorized: ${why}`);
    ack.resolve(authorized);
  }

  private clearResetAck(): void {
    if (this.resetAck) {
      if (this.resetAck.timer) clearTimeout(this.resetAck.timer);
      detachedAbortListener(this.resetAck.signal, this.resetAck.abortListener);
      this.resetAck = null;
    }
  }

  /** Spawn the RPC child and wait for the ready frame. */
  private spawn(model: string): Promise<void> {
    const { promise, resolve, reject } = Promise.withResolvers<void>();
    const proc = this.childFactory(model);
    this.proc = proc;
    this.currentModel = model;
    this.generation += 1;
    this.logger.log(
      `judge: spawned ${redactForLog(`${[this.launch.command, ...this.launch.prefixArgs].join(" ")} --mode rpc --model ${model}`)} pid=${proc.pid}`,
    );

    let stderrBuf = "";
    proc.stderr?.on("data", (d: Buffer) => {
      stderrBuf = (stderrBuf + d.toString()).slice(-2000);
    });

    const rl = readline.createInterface({ input: proc.stdout!, crlfDelay: Infinity });
    this.rl = rl;

    let ready = false;
    const onLine = (line: string) => {
      let frame: RpcFrame;
      try {
        frame = JSON.parse(line);
      } catch {
        return;
      }
      if (!ready) {
        if (frame.type === "ready") {
          ready = true;
          this.logger.log(`judge: ready protocol=${frame.protocolVersion}`);
          resolve();
        }
        // ignore pre-ready frames
        return;
      }
      this.handleFrame(frame);
    };
    rl.on("line", onLine);

    proc.on("error", (err) => {
      const message = err instanceof Error ? err.message : String(err);
      this.logger.log(`judge: spawn error: ${redactForLog(message)}`);
      const current = shouldClearProcRef(this.proc, proc);
      if (current) {
        this.proc = null;
        this.rl = null;
      }
      if (!ready) reject(err instanceof Error ? err : new Error(message));
      // A replaced (stale) child's error must not fail the NEWER child's
      // in-flight prompt: only the current generation fails pending.
      else if (current) this.failPending(`process error: ${message}`, "exit");
    });
    proc.on("exit", (code, signal) => {
      this.logger.log(`judge: process exited code=${code} signal=${signal} stderr=${redactForLog(stderrBuf.slice(-500))}`);
      const current = shouldClearProcRef(this.proc, proc);
      if (current) {
        this.proc = null;
        this.rl = null;
      }
      // Surface the child's stderr in the failure reason: a child that dies
      // almost always explains why (e.g. 'Model ... not found' for an
      // unresolvable model spec), and without it the gate's denial is an
      // opaque category the operator cannot act on.
      const stderrTail = redactForLog(stderrBuf.slice(-200));
      if (!ready) reject(new Error(`judge process exited before ready (code ${code})${stderrTail ? `: ${stderrTail}` : ""}`));
      else if (current) this.failPending(`process exited (code ${code})${stderrTail ? `: ${stderrTail}` : ""}`, "exit");
    });
    return promise;
  }

  /** Dispatch an inbound frame after ready. */
  private handleFrame(frame: RpcFrame): void {
    switch (frame.type) {
      case "response": {
        if (frame.command === "new_session") {
          // new_session ack for the per-assessment reset. Only a successful
          // ack carrying the currently expected id settles the reset;
          // mismatched or stale acks are noise the reset ignores (its window
          // then fails the assessment closed).
          if (this.resetAck && frame.id === this.resetAck.id) {
            const { authorized, reason } = newSessionOutcome(frame);
            this.resolveReset(authorized, reason);
          }
          return;
        }
        if (frame.command === "prompt") {
          const pending = this.pending;
          if (!pending || frame.id !== pending.id) {
            this.logger.log(`judge: ignoring prompt response for stale id ${frame.id ?? "(missing)"}`);
            break;
          }
          let agentInvoked: unknown;
          if (frame.data !== null && typeof frame.data === "object" && "agentInvoked" in frame.data) {
            agentInvoked = (frame.data as Record<string, unknown>).agentInvoked;
          }
          if (agentInvoked === false) {
            // Local-only completion: no agent turn will start, so no
            // agent_end will arrive. Settle now instead of waiting out
            // the timeout.
            this.logger.log("judge: prompt resolved locally (agentInvoked=false)");
            this.settle({ kind: "empty", reason: "resolved locally (agentInvoked=false)" });
          } else if (frame.success !== true) {
            const reason = redactForLog(String(frame.error ?? "prompt rejected"));
            this.logger.log(`judge: prompt rejected: ${reason}`);
            this.settle({ kind: "error", reason, category: "provider" });
          } else {
            pending.promptAccepted = true;
            this.logEvent(this.generation, pending.id, pending.startedAt, "prompt ack");
          }
        }
        break;
      }
      case "agent_start": {
        if (this.pending?.promptAccepted) {
          this.pending.agentStarted = true;
          this.logEvent(this.generation, this.pending.id, this.pending.startedAt, "agent start");
        }
        break;
      }
      case "message_update": {
        // Accumulate streaming text deltas. The final verdict comes from
        // agent_end.messages; deltas are the diagnostic signal that lets
        // the invoker tell reasoning-only output from a truly empty
        // completion.
        const ev = (frame as { assistantMessageEvent?: { type?: string; delta?: string } }).assistantMessageEvent;
        if (ev?.type === "text_delta" && typeof ev.delta === "string" && this.pending) {
          this.pending.deltaBuffer += ev.delta;
          if (!this.pending.deltaArrived) {
            this.pending.deltaArrived = true;
            this.pending.firstDeltaAt = Date.now();
          }
        }
        break;
      }
      case "agent_end": {
        if (!this.pending) break;
        if (!this.pending.agentStarted) {
          this.logger.log("judge: ignoring agent_end before current turn started");
          break;
        }
        if (!shouldSettleAgentEnd({ isTerminal: frame.isTerminal })) {
          this.logger.log("judge: ignoring non-terminal agent_end");
          break;
        }
        const text = extractFinalAssistantText(frame.messages);
        const p = this.pending;
        const firstDelta = p.firstDeltaAt !== undefined ? Math.max(0, p.firstDeltaAt - p.startedAt) : null;
        if (text) {
          this.settle({ kind: "text", text });
          this.logEvent(this.generation, p.id, p.startedAt, "verdict",
            `textLen=${text.length} deltaLen=${p.deltaBuffer.length}${firstDelta !== null ? ` firstDeltaMs=${firstDelta}` : ""}`);
        } else {
          const recovered = p.deltaBuffer.trim();
          if (recovered && parseJudgeVerdict(recovered)) {
            // The canonical agent_end.messages shape was empty but the
            // verdict was already delivered via text_delta (delta-fallback).
            // Recover it — but only when it parses as a valid verdict, so a
            // reasoning stream never masquerases as one.
            this.logger.log(`judge: agent_end carried no assistant text; recovering verdict from streamed deltas len=${recovered.length}`);
            this.settle({ kind: "text", text: recovered });
          } else {
            this.logger.log(`judge: agent_end with no assistant text (${emptyCompletionReason(p.deltaArrived)})`);
            this.settle({ kind: "empty", reason: emptyCompletionReason(p.deltaArrived) });
          }
        }
        break;
      }
      case "prompt_result": {
        if ((frame as { agentInvoked?: boolean }).agentInvoked === false) {
          this.logger.log("judge: prompt resolved locally (prompt_result)");
          this.settle({ kind: "empty", reason: "resolved locally (prompt_result)" });
        }
        break;
      }
      case "extension_error":
        this.logger.log(`judge: extension_error: ${redactForLog(String(frame.error ?? ""))}`);
        break;
      default:
        break;
    }
  }

  /** Settle the in-flight prompt with a classified outcome and cancel its
   *  request-scoped timers. Idempotent: the first settlement wins — a later
   *  exit/kill cannot reclassify an outcome already settled at its cause
   *  site (e.g. a timeout that retired the child). */
  private settle(outcome: PromptOutcome): void {
    const p = this.pending;
    if (!p) return;
    this.pending = null;
    clearTimeout(p.timer);
    clearTimeout(p.abortTimer);
    detachedAbortListener(p.signal, p.abortListener);
    p.outcome = withAbort(p, outcome);
    p.resolve(p.outcome);
  }

  /**
   * Fail the in-flight prompt and, if mid-reset, fail that too. Callers
   * (spawn error/exit handlers) must only invoke this for the CURRENT child
   * generation: a replaced child's late failure must not clobber the pending
   * prompt that belongs to the newer child.
   */
  private failPending(reason: string, category: ProtocolErrorCategory): void {
    const p = this.pending;
    this.pending = null;
    if (p) {
      clearTimeout(p.timer);
      clearTimeout(p.abortTimer);
      detachedAbortListener(p.signal, p.abortListener);
      if (!p.outcome) {
        p.outcome = withAbort(p, { kind: "error", reason, category });
        p.resolve(p.outcome);
      }
      // Only a prompt that was actually in flight "failed"; an idle or
      // model-switch kill must not log a phantom failure.
      this.logger.log(`judge: prompt failed: ${redactForLog(reason)}`);
    }
    if (this.resetAck) this.resolveReset(false, reason);
  }

  /** Ask the child to abort; retire it if this exact prompt does not settle. */
  private abort(): void {
    const p = this.pending;
    if (!p || p.abortTimer) return;
    this.write({ type: "abort" });
    p.abortTimer = setTimeout(() => {
      if (this.pending?.id !== p.id) return;
      this.logger.log(`judge: prompt ${p.id} did not abort within ${this.abortGraceMs}ms, retiring child`);
      this.kill();
    }, this.abortGraceMs);
    p.abortTimer.unref?.();
  }

  /** Write one JSONL frame to the child stdin. */
  private write(frame: RpcFrame): void {
    if (!this.proc?.stdin?.writable) return;
    this.proc.stdin.write(JSON.stringify(frame) + "\n");
  }
}

/** One usable deep-analysis result. */
export interface DeepAnalysis {
  /** The deep model's reply: a JSON verdict when well-formed, prose otherwise. */
  text: string;
  /** The model that produced it (deepModel or its @smol fallback). */
  model: string;
  /** Parsed verdict, or null when the reply carried no usable one. */
  verdict: JudgeVerdict | null;
}

/** Run the deep-analysis pass on the given invoker: the first role of
 *  DEEP_MODELS (@tiny), then @smol when it cannot produce text. Returns
 *  null when no candidate yields text — the caller then shows its
 *  analysis-unavailable body. The result carries the parsed verdict so the
 *  caller can auto-approve a command the deep model clears, and escalate to
 *  a human only on real risk.  `opts.script` carries the referenced-script
 *  contents section, built once by the caller and reused by every candidate
 *  model. */
export async function runDeepAnalysis(
  invoker: JudgeInvoker,
  command: string,
  opts: { subjectMaxChars?: number; cwd?: string; context?: string; script?: string; timeoutMs: number; signal?: AbortSignal },
  logger?: LoggerLike,
): Promise<DeepAnalysis | null> {
  const prompt = buildDeepPrompt(command, opts.subjectMaxChars ?? 4000, opts.cwd, opts.context, opts.script);
  for (const model of DEEP_MODELS) {
    if (opts.signal?.aborted) return null;
    let outcome: PromptOutcome | null;
    try {
      outcome = await invoker.promptWithOutcome(model, prompt, { timeoutMs: opts.timeoutMs, signal: opts.signal });
    } catch (e) {
      logger?.log(`deep: ${model} threw: ${e instanceof Error ? e.message : String(e)}`);
      outcome = null;
    }
    if (outcome && outcome.kind === "text" && outcome.text.trim()) {
      const text = outcome.text.trim();
      return { text, model, verdict: parseJudgeVerdict(text) };
    }
    logger?.log(
      `deep: ${model} unavailable (${outcome ? (outcome.kind === "error" ? `error:${outcome.category}` : outcome.kind) : "null"})`,
    );
  }
  return null;
}

/** An explicit request abort dominates the terminal classification:
 *  the operator cancelled this request, so report "abort" regardless of
 *  the underlying terminal event (timeout, exit, or a late child response). */
function withAbort(p: PendingPrompt, outcome: PromptOutcome): PromptOutcome {
  return p.aborted
    ? { kind: "error", reason: "aborted by signal", category: "abort" }
    : outcome;
}